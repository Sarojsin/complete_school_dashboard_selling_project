    FOREIGN KEY (restricted_to_course) REFERENCES college_courses(id) ON DELETE SET NULL,
    FOREIGN KEY (receipt_generated_by) REFERENCES college_teachers(id) ON DELETE SET NULL,
    CHECK (amount > 0),
    CHECK (installment_count >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Alumni donation and gift tracking';

