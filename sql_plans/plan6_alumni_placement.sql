CREATE TABLE IF NOT EXISTS college_internship_evaluations (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    application_id BIGINT UNSIGNED UNIQUE NOT NULL, -- one evaluation per application
    evaluated_by BIGINT UNSIGNED NOT NULL, -- faculty supervisor
    technical_skills_rating INT CHECK (technical_skills_rating BETWEEN 1 AND 10),
    professional_conduct_rating INT CHECK (professional_conduct_rating BETWEEN 1 AND 10),
    punctuality_rating INT CHECK (punctuality_rating BETWEEN 1 AND 10),
    communication_rating INT CHECK (communication_rating BETWEEN 1 AND 10),
    task_completion_rating INT CHECK (task_completion_rating BETWEEN 1 AND 10),
    overall_rating DECIMAL(4,2) AS ((technical_skills_rating + professional_conduct_rating + punctuality_rating + communication_rating + task_completion_rating) / 5) STORED,
    supervisor_feedback TEXT,
    student_self_evaluation TEXT,
    project_deliverables JSON, -- files or links
    skills_acquired JSON,
    hours_worked INT UNSIGNED,
    days_present INT UNSIGNED,
    recommendation_letter_sent BOOLEAN DEFAULT FALSE,
    recommendation_letter_url TEXT,
    is_eligible_for_credit BOOLEAN DEFAULT FALSE,
    credit_hours_awarded INT,
    evaluation_completed BOOLEAN DEFAULT FALSE,
    evaluation_completed_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_application (application_id),
    INDEX idx_evaluator (evaluated_by),
    INDEX idx_rating (overall_rating),
    FOREIGN KEY (application_id) REFERENCES college_internship_applications(id) ON DELETE CASCADE,
    FOREIGN KEY (evaluated_by) REFERENCES college_teachers(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Faculty evaluation of student internship performance';

