    receipt_number VARCHAR(100),
    receipt_date DATE,
    tax_benefit_eligible BOOLEAN DEFAULT FALSE,
    tax_exemption_certificate_sent BOOLEAN DEFAULT FALSE,
    dedication TEXT, -- "In memory of...", "For department..."
    restricted_to_department BIGINT UNSIGNED,
    restricted_to_course BIGINT UNSIGNED,
    is_anonymous BOOLEAN DEFAULT FALSE,
    gift_matching_company VARCHAR(255),
    installment_count INT DEFAULT 1,
    installment_frequency ENUM('monthly', 'quarterly', 'annually'),
    next_installment_date DATE,
    campaign_id BIGINT UNSIGNED,
    notes TEXT,
    receipt_generated_at TIMESTAMP NULL,
    receipt_generated_by BIGINT UNSIGNED,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_donation_number (donation_number),
    INDEX idx_donor (donor_id),
    INDEX idx_date (donation_date),
    INDEX idx_type (donation_type),
    INDEX idx_receipt (receipt_number),
