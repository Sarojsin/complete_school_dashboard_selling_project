-- -----------------------------------------------------------------------------
-- 6.1 COLLEGE_ALUMNI_RECORDS
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS college_alumni_records (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    alumni_number VARCHAR(50) UNIQUE NOT NULL,
    student_id BIGINT UNSIGNED UNIQUE, -- original student record
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    phone_primary VARCHAR(20),
    phone_secondary VARCHAR(20),
    date_of_birth DATE,
    gender ENUM('male', 'female', 'other', 'prefer_not_to_say'),
    blood_group ENUM('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'),
    graduation_year INT NOT NULL,
    graduation_month ENUM('jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec') DEFAULT 'may',
    degree_type ENUM('bachelor', 'master', 'diploma', 'certificate', 'phd') NOT NULL,
    department_id BIGINT UNSIGNED NOT NULL,
    course_id BIGINT UNSIGNED NOT NULL,
    specialization VARCHAR(255),
    roll_number VARCHAR(100),
    cgpa DECIMAL(4,2),
    division VARCHAR(10),
    current_job_title VARCHAR(255),
    current_company VARCHAR(255),
    industry_sector VARCHAR(255),
    job_type ENUM('full_time', 'part_time', 'freelance', 'self_employed', 'unemployed', 'studying') DEFAULT 'full_time',
    experience_years DECIMAL(4,1) DEFAULT 0.0,
    current_salary DECIMAL(14,2),
    salary_currency VARCHAR(3) DEFAULT 'INR',
    current_city VARCHAR(100),
    current_state VARCHAR(100),
    current_country VARCHAR(100) DEFAULT 'India',
    linkedin_url TEXT,
    facebook_url TEXT,
    twitter_handle VARCHAR(100),
    website_portfolio TEXT,
    skills JSON, -- ["python", "java", "project_management"]
    certifications JSON,
    languages_known JSON,
    is_visible_in_directory BOOLEAN DEFAULT TRUE,
    is_willing_to_mentor BOOLEAN DEFAULT FALSE,
    is_willing_to_hire BOOLEAN DEFAULT FALSE,
    wants_job_alerts BOOLEAN DEFAULT TRUE,
    newsletter_subscription BOOLEAN DEFAULT TRUE,
    last_contacted_date DATE,
    last_contact_method ENUM('email', 'phone', 'meeting', 'event', 'other'),
    engagement_score INT DEFAULT 0, -- calculated from activity
    notes TEXT,
    data_source ENUM('student_record', 'self_registered', 'linkedin_import', 'manual') DEFAULT 'student_record',
    profile_complete_percentage INT DEFAULT 0,
    last_updated_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_alumni_number (alumni_number),
    INDEX idx_student (student_id),
    INDEX idx_graduation (graduation_year, department_id),
    INDEX idx_dept_course (department_id, course_id),
    INDEX idx_email (email),
    INDEX idx_location (current_city, current_state, current_country),
    INDEX idx_company (current_company),
    INDEX idx_skills (skills), -- JSON search depends on MySQL version
    INDEX idx_engagement (engagement_score),
    INDEX idx_mentor (is_willing_to_mentor),
    INDEX idx_visible (is_visible_in_directory),
    FULLTEXT idx_search (first_name, last_name, current_company, current_job_title, skills),
    FOREIGN KEY (student_id) REFERENCES college_students(id) ON DELETE SET NULL,
    FOREIGN KEY (department_id) REFERENCES college_departments(id) ON DELETE RESTRICT,
    FOREIGN KEY (course_id) REFERENCES college_courses(id) ON DELETE RESTRICT,
    CHECK (engagement_score >= 0 AND engagement_score <= 100),
    CHECK (experience_years >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Master alumni records with career tracking';

